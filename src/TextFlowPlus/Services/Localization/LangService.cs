namespace TextFlowPlus.Services.Localization;

/// <summary>界面语言。</summary>
public enum AppLanguage
{
    Chinese,
    English,
    Japanese
}

/// <summary>
/// 界面多语言服务：以中文为原始文本，切换到英文/日语时按字典翻译。
/// 字典未覆盖的文本保持中文。切换时触发 <see cref="LanguageChanged"/> 供各面板刷新。
/// </summary>
public static class LangService
{
    public static AppLanguage Language { get; private set; } = AppLanguage.Chinese;

    public static event Action? LanguageChanged;

    public static bool IsEn => Language == AppLanguage.English;
    public static bool IsJa => Language == AppLanguage.Japanese;
    /// <summary>是否处于需要翻译的状态（非中文原文）。</summary>
    public static bool NeedsTranslation => Language != AppLanguage.Chinese;

    public static void SetLanguage(AppLanguage lang)
    {
        if (Language == lang) return;
        Language = lang;
        LanguageChanged?.Invoke();
    }

    /// <summary>翻译：英文/日语模式下返回对应译文（未收录则原文），中文模式返回原文。</summary>
    public static string T(string zh)
    {
        if (!NeedsTranslation) return zh;
        var dict = IsJa ? _ja : _en;
        return dict.TryGetValue(zh, out var v) ? v : zh;
    }

    /// <summary>翻译带占位符的消息：{0} {1} …。</summary>
    public static string TFormat(string zh, params object[] args)
    {
        return string.Format(T(zh), args);
    }

